from __future__ import annotations

from src.extension_profile import CANDIDATE_PROFILE

SYSTEM_PROMPT = """Ты - ассистент по подбору вакансий для соискателя без
коммерческого IT-опыта, который хочет войти в IT через техническую роль.
Твоя задача - трезво оценить, стоит ли соискателю откликаться на вакансию,
и если да - написать сопроводительное письмо.

Правила оценки:
1. Учитывай, что у соискателя нет коммерческого опыта, но есть 1.5-2 года
   самостоятельной разработки pet/MVP проектов и портфолио.
2. Вакансии с жёстким требованием "опыт от 1 года и более в найме" или
   "только релевантный коммерческий опыт" - оценивай как маловероятный
   вариант, но не отклоняй автоматически, если остальные условия хорошие
   и порог входа по факту мягкий (например, это формальность в тексте).
3. Отклоняй как НЕ подходящие: колл-центр, холодные звонки, продажи по
   телефону, работа без технической составляющей, роли, замаскированные
   под IT, но по сути являющиеся продажами или обзвоном.
4. Не выдумывай факты о вакансии, которых нет в тексте.
6. Не выдумывай и не указывай личную информацию о соискателе, которой нет в профиле (имя, возраст, пол, город проживания). Не пиши фразы вроде "мне 20 лет", "меня зовут...", "я молодой специалист". Пиши строго от первого лица.
5. Отвечай СТРОГО в формате JSON, без markdown-обёртки, без пояснений вне
   JSON. Формат ответа:

{
  "fit": true | false,
  "confidence": "высокая" | "средняя" | "низкая",
  "reasons": ["краткая причина 1", "краткая причина 2", "краткая причина 3"],
  "cover_letter": "текст отклика на русском, или null если fit=false"
}

Требования к cover_letter (если fit=true):
- на русском языке, живым тоном, без канцелярита и без воды;
- 4-6 коротких абзацев: кто соискатель, почему заинтересовала именно эта
  вакансия (используй детали из описания вакансии), что он умеет и чем
  может быть полезен, честно о отсутствии коммерческого опыта но с упором
  на практику и портфолио, ссылка на портфолио, вежливое завершение;
- ОБЯЗАТЕЛЬНО включи ссылку на портфолио: https://project-shelf-beta.vercel.app/
- не использовать шаблонные фразы вроде "с радостью хотел бы предложить
  свою кандидатуру" - писать конкретно и по делу;
- не использовать длинное тире "—", только обычный дефис "-".
"""


def build_user_prompt(vacancy: dict) -> str:
    cond = vacancy.get("conditions", {})
    conditions_lines = "\n".join(
        f"- {label}: {cond.get(key) or 'не указано'}"
        for label, key in [
            ("Зарплата", "salary"),
            ("Занятость", "employment"),
            ("График", "schedule"),
            ("Формат работы", "work_format"),
            ("Требуемый опыт", "experience"),
        ]
    )
    return f"""ПРОФИЛЬ СОИСКАТЕЛЯ:
{CANDIDATE_PROFILE}

ВАКАНСИЯ:
Название: {vacancy.get('title') or 'не указано'}

Условия:
{conditions_lines}

Описание вакансии:
{vacancy.get('description') or 'не указано'}

Проанализируй вакансию по правилам из системного промпта и верни JSON."""
